// 内部发送消息处理（API 模式）
const handleInternalSend = async (
  query: string,
  fileList: FileProps[],
  conversationId: string,
  applicationId: string,
) => {
  if (isUploading.value) return;
  if (!useApiMode.value) {
    if (props.frontendPocMode && mockChatEnabled.value) {
      const streamConversationKey =
        currentConversationStateKey.value || "poc-conversation";
      currentConversationStateKey.value = streamConversationKey;
      const streamState = ensureConversationRuntimeState(streamConversationKey);
      if (!streamState) return;

      const timestamp = Date.now();
      const baseExtraInfo = (isFromSelf: boolean, offset = 0) => ({
        RequestId: "",
        TraceId: "",
        Elapsed: 0,
        StartTime: timestamp + offset,
        IsFromSelf: isFromSelf,
        CanRating: false,
        CanFeedback: false,
      });
      const createTextRecord = (
        role: "assistant" | "user",
        recordId: string,
        messageType: "reply" | "question",
        text: string,
        offset = 0,
      ): Record => ({
        Role: role,
        RecordId: recordId,
        ConversationId: streamConversationKey,
        Status: "success",
        StatusDesc: "",
        Messages: [
          {
            Type: messageType,
            MessageId: `${recordId}-message`,
            Name: messageType,
            Title: "",
            Status: "success",
            StatusDesc: "",
            Contents: [{ Type: "text", Text: text }],
          },
        ],
        ExtraInfo: baseExtraInfo(role === "user", offset),
      });

      streamState.records.push(
        createTextRecord("user", `poc-user-${timestamp}`, "question", query),
        createTextRecord(
          "assistant",
          `poc-assistant-${timestamp}`,
          "reply",
          activeChatbotConfig.value?.mockChat.reply ||
            (isEnglish.value
              ? "This is a frontend POC reply. The real chatbot backend will be connected later."
              : "這是前端 POC 回覆，正式聊天功能會在後端整合階段接入。"),
          1,
        ),
      );
      nextTick(() => {
        mainLayoutRef.value?.getChatRef()?.backToBottom();
      });
      return;
    }
    if (props.frontendPocMode) {
      return;
    }
    emit("send", query, fileList, conversationId, applicationId);
    return;
  }

  let streamConversationKey =
    conversationId ||
    currentConversationStateKey.value ||
    createPendingConversationKey();
  currentConversationStateKey.value = streamConversationKey;
  const streamState = ensureConversationRuntimeState(streamConversationKey);
  if (!streamState) {
    return;
  }
  streamState.isChatting = true;
  streamState.applicationId =
    applicationId ||
    streamState.applicationId ||
    internalCurrentConversation.value?.ApplicationId ||
    internalCurrentApplication.value?.ApplicationId;
  // 重置用户滚动状态
  mainLayoutRef.value?.getChatRef()?.setHasUserScrolled(false);

  const timestamp = Date.now();
  const localAudioFile = getLocalAudioFile(fileList);
  const userPlaceholderId = localAudioFile
    ? getLocalAudioRecordId(localAudioFile)
    : "placeholder-user";
  const baseExtraInfo = (isFromSelf: boolean) => ({
    RequestId: "",
    TraceId: "",
    Elapsed: 0,
    StartTime: timestamp,
    IsFromSelf: isFromSelf,
  });

  // 构建用户消息展示内容（图片和文档都作为 file Content 展示）
  const userContents: Content[] = [{ Type: "text", Text: query }];
  for (const file of fileList) {
    const fileContent = fileToContent(file);
    if (fileContent) userContents.push(fileContent);
  }

  // 创建用户消息占位
  const userRecord: Record = {
    Role: "user",
    RecordId: userPlaceholderId,
    ConversationId: conversationId || streamConversationKey,
    Status: "success",
    StatusDesc: "",
    Messages: [
      {
        Type: "question",
        MessageId: `placeholder-user-${timestamp}`,
        Name: "question",
        Title: "",
        Status: "success",
        StatusDesc: "",
        Contents: userContents,
      },
    ],
    ExtraInfo: baseExtraInfo(true),
  };
  const existingUserRecordIndex = streamState.records.findIndex(
    (record) => record.RecordId === userPlaceholderId,
  );
  if (existingUserRecordIndex >= 0) {
    streamState.records.splice(existingUserRecordIndex, 1, userRecord);
  } else {
    streamState.records.push(userRecord);
  }

  // 创建助手消息占位
  const assistantRecord: Record = {
    Role: "assistant",
    RecordId: "placeholder-agent",
    ConversationId: conversationId || streamConversationKey,
    Status: "processing",
    StatusDesc: "",
    Messages: [],
    ExtraInfo: baseExtraInfo(false),
  };
  streamState.records.push(assistantRecord);

  // 发送消息后滚动到底部
  nextTick(() => {
    mainLayoutRef.value?.getChatRef()?.backToBottom();
  });

  streamState.abortController = new AbortController();

  const contents: Content[] = [{ Type: "text", Text: query }];
  // 将所有已上传成功的文件（图片和文档）以 file content 格式加入
  for (const file of fileList) {
    if (file.localOnly) continue;
    const fileContent = fileToContent(file);
    if (fileContent) contents.push(fileContent);
  }
  const backendFileList = fileList.filter((file) => !file.localOnly);
  await fetchSSE(
    () => {
      return sendMessage(
        {
          Contents: contents,
          ConversationId: conversationId || undefined,
          ApplicationId: applicationId,
          FileInfos: backendFileList,
          Language: backendLanguage.value,
          CustomVariables: languageCustomVariables.value,
        },
        { signal: streamState.abortController?.signal },
        mergedApiDetailConfig.value.sendMessageApi,
      );
    },
    {
      success(event: SseEvent) {
        if (event.Type === "conversation") {
          upsertConversation(event.Payload);
          // 创建新的对话，重新调用 chatlist 接口更新列表
          loadConversations();
          if (event.Payload.IsNewConversation) {
            const previousKey = streamConversationKey;
            streamConversationKey = moveConversationRuntimeState(
              previousKey,
              event.Payload.Id,
              event.Payload.ApplicationId || streamState.applicationId,
            );
            if (currentConversationStateKey.value === previousKey) {
              currentConversationStateKey.value = streamConversationKey;
            }
          }
          if (currentConversationStateKey.value === event.Payload.Id) {
            internalCurrentConversation.value = {
              ...(internalCurrentConversation.value || event.Payload),
              ...event.Payload,
            };
          }
          return;
        }

        const targetState = ensureConversationRuntimeState(
          streamConversationKey,
        );
        if (!targetState) {
          return;
        }
        const resolvedApplicationId =
          targetState.applicationId ||
          applicationId ||
          internalCurrentApplication.value?.ApplicationId;

        const replacePlaceholder = (
          placeholderId: string,
          next: Record,
        ): Record | undefined => {
          const placeholderIdx = targetState.records.findIndex(
            (item) => item.RecordId === placeholderId,
          );
          if (placeholderIdx !== -1) {
            targetState.records.splice(placeholderIdx, 1, next);
            return next;
          }
          return undefined;
        };

        const updateRecord = (next: Record, placeholderId: string): Record => {
          const idx = targetState.records.findIndex(
            (item) => item.RecordId === next.RecordId,
          );
          if (idx !== -1) {
            if (targetState.records[idx] !== undefined) {
              Object.assign(targetState.records[idx], next);
              return targetState.records[idx] as Record;
            }
            return next;
          }
          const replaced = replacePlaceholder(placeholderId, next);
          if (replaced) {
            return replaced;
          }
          targetState.records.push(next);
          return next;
        };

        if (event.Type === "request_ack") {
          // 用户消息：替换占位
          const placeholderUser = targetState.records.find(
            (item) => item.RecordId === userPlaceholderId,
          );
          const nextUser = applySseEventToRecord(event, placeholderUser);
          if (nextUser) {
            const userWithLocalAudio = appendLocalOnlyFileContents(
              nextUser,
              placeholderUser,
            );
            const appliedUser = updateRecord(userWithLocalAudio, userPlaceholderId);
            void hydrateReferences([appliedUser], {
              applicationId: resolvedApplicationId,
            });
          }
        } else {
          // 助手消息：只用占位 + lastRecord
          const lastIndex = targetState.records.length - 1;
          const lastRecord = targetState.records[lastIndex];
          const baseAssistant =
            lastRecord &&
            (lastRecord.RecordId === "placeholder-agent" ||
              lastRecord.Role === "assistant")
              ? lastRecord
              : undefined;
          const nextAssistant = applySseEventToRecord(event, baseAssistant);
          if (nextAssistant) {
            const appliedAssistant = updateRecord(
              nextAssistant,
              "placeholder-agent",
            );
            void hydrateReferences([appliedAssistant], {
              applicationId: resolvedApplicationId,
            });
          }
        }

        // 每次收到数据后滚动到底部
        if (currentConversationStateKey.value === streamConversationKey) {
          nextTick(() => {
            mainLayoutRef.value?.getChatRef()?.backToBottom();
          });
        }
      },
      complete(isOk) {
        const targetState = getConversationRuntimeState(streamConversationKey);
        if (targetState) {
          targetState.isChatting = false;
          targetState.abortController = null;
        }
        if (!isOk) {
          return;
        }
        // 完成后滚动到底部并延迟重置用户滚动状态
        if (currentConversationStateKey.value === streamConversationKey) {
          nextTick(() => {
            mainLayoutRef.value?.getChatRef()?.backToBottom();
            setTimeout(() => {
              mainLayoutRef.value?.getChatRef()?.setHasUserScrolled(false);
            }, 500);
          });
        }
      },
      fail(msg) {
        const failureText = handleStreamFailure(msg);
        if (failureText) {
          markLatestAssistantError(streamConversationKey, failureText);
        }
      },
    },
  );
};

