const currentTermsSectionKey = computed(() => {
  if (!termsGateEnabled.value) return "disabled";
  const storageScope =
    activeChatbotConfig.value?.terms.storageScope || "conversation";
  const appKey =
    activeChatbotConfig.value?.appId || currentApplicationId.value || "pending";
  if (storageScope === "global") return `global:${appKey}`;
  if (storageScope === "application") return `application:${appKey}`;
  const conversationId =
    currentConversationId.value || currentConversationStateKey.value;
  if (conversationId) return `conversation:${conversationId}`;
  if (currentApplicationId.value)
    return `application:${currentApplicationId.value}:new`;
  return "application:pending";
});
const currentTermsStorageKey = computed(
  () => `${TERMS_ACCEPTED_STORAGE_PREFIX}:${currentTermsSectionKey.value}`,
);
const termsResolving = computed(
  () =>
    currentTermsSectionKey.value === "application:pending" &&
    !applicationsResolved.value &&
    props.applications.length === 0 &&
    !props.currentApplication &&
    !props.currentApplicationId,
);

watch(
  currentTermsStorageKey,
  (newStorageKey, oldStorageKey) => {
    const shouldTransferToCreatedConversation =
      Boolean(oldStorageKey) &&
      termsAccepted.value &&
      lastAcceptedTermsStorageKey.value === oldStorageKey &&
      currentTermsSectionKey.value.startsWith("conversation:");

    if (shouldTransferToCreatedConversation) {
      if (typeof window !== "undefined") {
        window.localStorage.setItem(newStorageKey, "1");
      }
      lastAcceptedTermsStorageKey.value = newStorageKey;
      termsAccepted.value = true;
      return;
    }

    termsAccepted.value = getStoredTermsAccepted(newStorageKey);
    termsPromptKey.value += 1;
  },
  { immediate: true },
);

const handleAcceptTerms = () => {
  if (!termsGateEnabled.value) return;
  const storageKey = currentTermsStorageKey.value;
  termsAccepted.value = true;
  lastAcceptedTermsStorageKey.value = storageKey;
  if (typeof window !== "undefined") {
    window.localStorage.setItem(storageKey, "1");
  }
  nextTick(() => {
    mainLayoutRef.value?.getChatRef()?.backToBottom();
  });
};

const handleDeclineTerms = () => {
  if (!termsGateEnabled.value) return;
  const storageKey = currentTermsStorageKey.value;
  termsAccepted.value = false;
  termsPromptKey.value += 1;
  if (typeof window !== "undefined") {
    window.localStorage.removeItem(storageKey);
  }
  MessagePlugin.info(acceptTermsFirstMessage.value);
};

